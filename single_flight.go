package lock

import (
	"sync"
	"time"
)

type call[V any] struct {
	wg  sync.WaitGroup
	val V
	err error
}

type item[V any] struct {
	val V
	id  uint64
}

// SingleFlightMap is a highly optimized concurrent map with optional TTLs.
type SingleFlightMap[K comparable, V any] struct {
	mu    sync.RWMutex
	items map[K]item[V]

	seq    uint64
	timers map[K]*time.Timer

	cmu   sync.Mutex
	calls map[K]*call[V]
}

func NewSingleFlightMap[K comparable, V any]() *SingleFlightMap[K, V] {
	return &SingleFlightMap[K, V]{
		items:  make(map[K]item[V]),
		timers: make(map[K]*time.Timer),
		calls:  make(map[K]*call[V]),
	}
}

// Keys returns a slice of all keys currently in the map.
func (m *SingleFlightMap[K, V]) Keys() []K {
	m.mu.RLock()

	keys := make([]K, 0, len(m.items))

	for k := range m.items {
		keys = append(keys, k)
	}

	m.mu.RUnlock()

	return keys
}

// GetOrFill calls GetOrFillWithTTL with a 0 TTL (no expiration) and returns if the value was filled (if the generator was called).
func (m *SingleFlightMap[K, V]) GetOrFill(key K, generator func() (V, error)) (V, bool, error) {
	return m.GetOrFillWithTTL(key, 0, generator)
}

// GetOrFillWithTTL returns the value and if the value was filled (if the generator was called). If missing, it coordinates a single generator call.
// If ttl is > 0, the item will be automatically and fully removed from memory after the duration.
func (m *SingleFlightMap[K, V]) GetOrFillWithTTL(key K, ttl time.Duration, generator func() (V, error)) (V, bool, error) {
	m.mu.RLock()
	it, ok := m.items[key]
	m.mu.RUnlock()

	if ok {
		return it.val, false, nil
	}

	m.cmu.Lock()

	// double check
	m.mu.RLock()
	it, ok = m.items[key]
	m.mu.RUnlock()

	if ok {
		m.cmu.Unlock()

		return it.val, false, nil
	}

	if call, inFlight := m.calls[key]; inFlight {
		m.cmu.Unlock()

		call.wg.Wait()

		return call.val, false, call.err
	}

	c := new(call[V])

	c.wg.Add(1)

	m.calls[key] = c

	m.cmu.Unlock()

	defer func() {
		m.cmu.Lock()
		delete(m.calls, key)
		m.cmu.Unlock()

		c.wg.Done()
	}()

	c.val, c.err = generator()
	if c.err == nil {
		m.mu.Lock()

		if freshItem, alreadySet := m.items[key]; alreadySet {
			c.val = freshItem.val
		} else {
			m.seq++

			id := m.seq

			m.items[key] = item[V]{
				val: c.val,
				id:  id,
			}

			if oldTimer, exists := m.timers[key]; exists {
				oldTimer.Stop()
			}

			if ttl > 0 {
				m.timers[key] = time.AfterFunc(ttl, func() {
					m.mu.Lock()

					current, exists := m.items[key]
					if exists && current.id == id {
						delete(m.items, key)
						delete(m.timers, key)
					}

					m.mu.Unlock()
				})
			} else {
				delete(m.timers, key)
			}
		}

		m.mu.Unlock()
	}

	return c.val, true, c.err
}

// WillGetOrFill calls MustGetOrFillWithTTL with a 0 TTL (no expiration) and returns if the value was filled (if the generator was called).
func (m *SingleFlightMap[K, V]) WillGetOrFill(key K, generator func() V) (V, bool) {
	return m.WillGetOrFillWithTTL(key, 0, generator)
}

// WillGetOrFillWithTTL returns the value and if the value was filled (if the generator was called). If missing, it coordinates a single generator call.
// If ttl is > 0, the item will be automatically and fully removed from memory after the duration.
func (m *SingleFlightMap[K, V]) WillGetOrFillWithTTL(key K, ttl time.Duration, generator func() V) (V, bool) {
	val, filled, _ := m.GetOrFillWithTTL(key, ttl, func() (V, error) {
		return generator(), nil
	})

	return val, filled
}

// Get returns the value if it exists. It does NOT wait for in-flight generations.
func (m *SingleFlightMap[K, V]) Get(key K) (V, bool) {
	m.mu.RLock()
	it, ok := m.items[key]
	m.mu.RUnlock()

	return it.val, ok
}

// Set forcefully overwrites a key with no TTL and returns if the key already existed.
func (m *SingleFlightMap[K, V]) Set(key K, val V) bool {
	return m.SetWithTTL(key, val, 0)
}

// SetWithTTL forcefully overwrites a key, applies a TTL and returns if the key already existed.
func (m *SingleFlightMap[K, V]) SetWithTTL(key K, val V, ttl time.Duration) bool {
	m.mu.Lock()

	m.seq++

	id := m.seq

	m.items[key] = item[V]{
		val: val,
		id:  id,
	}

	oldTimer, exists := m.timers[key]
	if exists {
		oldTimer.Stop()
	}

	if ttl > 0 {
		m.timers[key] = time.AfterFunc(ttl, func() {
			m.mu.Lock()

			current, exists := m.items[key]
			if exists && current.id == id {
				delete(m.items, key)
				delete(m.timers, key)
			}

			m.mu.Unlock()
		})
	} else {
		delete(m.timers, key)
	}

	m.mu.Unlock()

	return exists
}

// Delete removes a key from the map and returns if it existed.
func (m *SingleFlightMap[K, V]) Delete(key K) bool {
	m.mu.Lock()

	delete(m.items, key)

	t, exists := m.timers[key]
	if exists {
		t.Stop()

		delete(m.timers, key)
	}

	m.mu.Unlock()

	return exists
}

// GetAndWait returns the value if it exists. If the value is currently
// being generated by another goroutine, it will pause and wait.
func (m *SingleFlightMap[K, V]) GetAndWait(key K) (V, bool) {
	m.mu.RLock()
	it, ok := m.items[key]
	m.mu.RUnlock()

	if ok {
		return it.val, true
	}

	m.cmu.Lock()

	// double check
	m.mu.RLock()
	it, ok = m.items[key]
	m.mu.RUnlock()

	if ok {
		m.cmu.Unlock()

		return it.val, true
	}

	c, inFlight := m.calls[key]
	if !inFlight {
		m.cmu.Unlock()

		var zero V

		return zero, false
	}

	m.cmu.Unlock()

	c.wg.Wait()

	if c.err != nil {
		var zero V

		return zero, false
	}

	return c.val, true
}
